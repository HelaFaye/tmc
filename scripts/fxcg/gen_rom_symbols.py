#!/usr/bin/env python3
"""Write port/fxcg/rom_symbols.ld: the ROM-resident symbols as addresses in
the fx-CG50 ROM window (docs/fx-cg50-port-plan.md, D1 and "Memory").

The PC build compiles port/data_const_stubs.c, which holds copies of 400 ROM
tables (about 1 MB). The calculator build leaves that file out and defines
each symbol at FXCG_ROM_WINDOW + its ROM offset instead, so the game reads
the tables through the same paged window as the rest of the ROM. The output
holds only names and offsets, no ROM bytes.

usage: gen_rom_symbols.py [port/data_const_stubs.c] [port/fxcg/rom_symbols.ld]
"""
import re
import sys

MAP_DATA_BASE_USA = 0x324AE4  # kRomOffsets_USA.mapDataBase in port/port_rom.c


def main(argv):
    src = argv[1] if len(argv) > 1 else "port/data_const_stubs.c"
    out = argv[2] if len(argv) > 2 else "port/fxcg/rom_symbols.ld"
    symbols = []
    offset = None
    for line in open(src):
        m = re.match(r"/\* \S+ @ ROM 0x([0-9A-Fa-f]+), (\d+) bytes \*/", line)
        if m:
            offset = int(m.group(1), 16)
            continue
        m = re.match(r"const u8 (\w+)\[(\d+)\]", line)
        if m:
            if offset is None:
                raise SystemExit("no ROM offset before " + m.group(1))
            symbols.append((m.group(1), offset))
            offset = None
    with open(out, "w") as f:
        f.write("/* Generated by scripts/fxcg/gen_rom_symbols.py from port/data_const_stubs.c.\n")
        f.write(" * ROM-resident symbols of the USA ROM, placed in the fx-CG50 ROM window.\n")
        f.write(" * FXCG_ROM_WINDOW is defined by port/fxcg/fxcg.ld. Do not edit. */\n\n")
        f.write("_gMapData = FXCG_ROM_WINDOW + 0x%06X;\n" % MAP_DATA_BASE_USA)
        for name, off in symbols:
            f.write("_%s = FXCG_ROM_WINDOW + 0x%06X;\n" % (name, off))
    print("%d symbols -> %s" % (len(symbols) + 1, out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
