#!/bin/sh
# Write port/fxcg/sources.cmake: the game's C files the fx-CG50 build compiles.
# The list is the PC build's own src/ objects (so the two builds compile the
# same game code); run `xmake build tmc_pc` first. Re-run when files are
# added to or removed from src/.
set -e
T=$(cd "$(dirname "$0")/../.." && pwd)
OUT="$T/port/fxcg/sources.cmake"
{
    echo "# Generated by scripts/fxcg/gen_sources.sh from the PC build's object list."
    echo "set(PICORI_GAME_SOURCES"
    (cd "$T/build/.objs/tmc_pc" && find . -path "*/src/*.o") | sed 's|.*/release/||; s|\.o$||' \
        | grep '^src/' | sort | sed 's|^|    ${TMC_ROOT}/|'
    echo ")"
} > "$OUT"
echo "$(grep -c TMC_ROOT "$OUT") files -> $OUT"
